"""Shared helpers for the Brick 3 goal tests (users, goal data, a fixed "today", audit dump).

If your project already has a user factory, change `make_user` to call it; nothing else here
depends on how users are built.
"""
import datetime as dt
from contextlib import contextmanager
from unittest import mock

from django.contrib.auth import get_user_model
from django.db import connection

from apps.accounts.models import Extension, PersonType, Role, Status

TODAY = dt.date(2026, 3, 4)          # a Wednesday (weekday 2)


def make_user(**overrides):
    """An active member who can sign in. account_id is generated by User.save(), so it is never passed."""
    extension = Extension.objects.get_or_create(name="Test Extension")[0]
    fields = dict(
        first_name="Juan", last_name="Dela Cruz", role=Role.MEMBER, extension=extension,
        person_type=PersonType.MEMBER_ACCOUNT, status=Status.ACTIVE, must_change_password=False,
    )
    fields.update(overrides)
    return get_user_model().objects.create_user(password="pass-12345-xyz", **fields)
@contextmanager
def at_date(day):
    """Pretend Manila's calendar date is `day` for every call to timezone.localdate()."""
    with mock.patch("django.utils.timezone.localdate", return_value=day):
        yield


@contextmanager
def cannot_sign_in():
    """Make every user look like a guest or no-account person (can_sign_in is False)."""
    User = get_user_model()
    with mock.patch.object(User, "can_sign_in", new_callable=mock.PropertyMock, return_value=False):
        yield


def goal_data(**over):
    """Valid data for create_goal: a daily all-day goal starting TODAY."""
    data = {
        "title": "Pray in the morning", "description": "Ten quiet minutes",
        "start_date": TODAY, "end_date": None, "start_time": None, "end_time": None,
        "repeat_type": "daily", "weekdays": None,
    }
    data.update(over)
    return data


def audit_dump():
    """Every audit_log row as JSON text, so a test can prove no goal text was logged."""
    with connection.cursor() as cursor:
        cursor.execute("SELECT row_to_json(a)::text FROM audit_log a")
        return "\n".join(row[0] for row in cursor.fetchall())


def notification_dump():
    """Every notification row as JSON text (goals send none in Brick 3; this guards the rule)."""
    with connection.cursor() as cursor:
        cursor.execute("SELECT to_regclass('notification')")
        if cursor.fetchone()[0] is None:
            return ""
        cursor.execute("SELECT row_to_json(n)::text FROM notification n")
        return "\n".join(row[0] for row in cursor.fetchall())
